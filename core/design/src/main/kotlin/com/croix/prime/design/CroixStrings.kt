fun resolveCroixStrings(mode: PrimeLanguageMode): CroixStrings = when (mode) {
    PrimeLanguageMode.SPANISH -> SpanishStrings
    PrimeLanguageMode.ENGLISH -> EnglishStrings
    PrimeLanguageMode.SYSTEM -> {
        if (Locale.getDefault().language.equals("es", ignoreCase = true)) SpanishStrings else EnglishStrings
    }
}

val LocalCroixStrings = staticCompositionLocalOf { resolveCroixStrings(PrimeLanguageMode.SYSTEM) }
